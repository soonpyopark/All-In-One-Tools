#!/usr/bin/env node
/**
 * Generates the app icons from one source image:
 *   build/icon.png      (1024, used by electron-builder / macOS / window icon)
 *   build/icon.ico      (Windows, 16–256)
 *   public/icon.png     (256, web UI logo)
 *   public/favicon.ico  (browser tab — Chrome prefers this path)
 *   shared/iconRev.js   (content hash for favicon / logo cache-busting)
 *
 * Source: build/icon-source.png. If it does not exist, a placeholder is drawn
 * from the SVG below — replace build/icon-source.png with your own artwork and
 * delete build/icon.png to regenerate. Outputs newer than the source are skipped
 * except iconRev.js, which is always kept in sync with the source hash.
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pngToIco from 'png-to-ico';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const buildDir = path.join(projectRoot, 'build');
const publicDir = path.join(projectRoot, 'public');
const sharedDir = path.join(projectRoot, 'shared');
const sourcePath = path.join(buildDir, 'icon-source.png');
const revPath = path.join(sharedDir, 'iconRev.js');

const PLACEHOLDER_SVG = `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#3b82f6"/>
      <stop offset="1" stop-color="#1d4ed8"/>
    </linearGradient>
  </defs>
  <rect width="1024" height="1024" rx="230" fill="url(#bg)"/>
  <rect x="212" y="236" width="600" height="552" rx="56" fill="none" stroke="#fff" stroke-width="48"/>
  <rect x="212" y="236" width="600" height="132" rx="56" fill="#fff"/>
  <rect x="212" y="312" width="600" height="56" fill="#fff"/>
  <path d="M408 368v420" stroke="#fff" stroke-width="40"/>
</svg>`;

const mtime = (file) => (fs.existsSync(file) ? fs.statSync(file).mtimeMs : 0);

function writeIconRev(rev) {
  const next = `/** Auto-generated by scripts/prepare-icons.mjs — do not edit. */\nexport const APP_ICON_REV = '${rev}';\n`;
  if (fs.existsSync(revPath) && fs.readFileSync(revPath, 'utf8') === next) return;
  fs.writeFileSync(revPath, next);
}

async function main() {
  fs.mkdirSync(buildDir, { recursive: true });
  fs.mkdirSync(publicDir, { recursive: true });
  fs.mkdirSync(sharedDir, { recursive: true });

  if (!fs.existsSync(sourcePath)) {
    await sharp(Buffer.from(PLACEHOLDER_SVG)).resize(1024, 1024).png().toFile(sourcePath);
    console.log('[icons] created placeholder build/icon-source.png');
  }

  const sourceBytes = fs.readFileSync(sourcePath);
  const rev = createHash('sha1').update(sourceBytes).digest('hex').slice(0, 8);
  writeIconRev(rev);

  const outputs = [
    path.join(buildDir, 'icon.png'),
    path.join(buildDir, 'icon.ico'),
    path.join(publicDir, 'icon.png'),
    path.join(publicDir, 'favicon.ico'),
  ];
  const sourceTime = mtime(sourcePath);
  if (outputs.every((file) => mtime(file) >= sourceTime)) {
    console.log(`[icons] up to date (rev ${rev})`);
    return;
  }

  const png = (size) => sharp(sourcePath).resize(size, size, { fit: 'cover' }).png().toBuffer();

  fs.writeFileSync(path.join(buildDir, 'icon.png'), await png(1024));
  fs.writeFileSync(path.join(publicDir, 'icon.png'), await png(256));

  const icoSizes = [16, 24, 32, 48, 64, 128, 256];
  const ico = await pngToIco(await Promise.all(icoSizes.map((size) => png(size))));
  fs.writeFileSync(path.join(buildDir, 'icon.ico'), ico);
  fs.writeFileSync(path.join(publicDir, 'favicon.ico'), ico);

  console.log(`[icons] build/icon.png, build/icon.ico, public/icon.png, public/favicon.ico ready (rev ${rev})`);
}

main().catch((error) => {
  console.error('[icons] failed:', error);
  process.exit(1);
});
